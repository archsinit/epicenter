const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
// Development-server visual tests only. Install Playwright in a separate test environment.
const baseUrl = process.env.GASTLY_PREVIEW_URL || 'http://127.0.0.1:1420';
const artifacts = process.env.GASTLY_TEST_ARTIFACTS || '/tmp/gastly-browser-artifacts';
fs.mkdirSync(artifacts, { recursive: true });
(async () => {
 const browser = await chromium.launch({ headless: true });
 const page = await browser.newPage({ viewport: {width: 1000, height: 800}, deviceScaleFactor: 2 });
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(baseUrl + '/companion-preview');
 await page.locator('.companion .face').waitFor();
 await page.waitForFunction(()=>[...document.querySelectorAll('.companion img')].every(i=>i.complete && i.naturalWidth));
 assert.equal(await page.locator('.companion').getAttribute('data-mode'),'idle');
 await page.screenshot({path:path.join(artifacts, 'idle.png')});
 const a=await page.locator('.head-look').evaluate(el=>getComputedStyle(el).transform);
 await page.mouse.move(950,50);await page.waitForTimeout(400);
 const b=await page.locator('.head-look').evaluate(el=>getComputedStyle(el).transform);assert.notEqual(a,b);
 await page.getByRole('button',{name:'recording',exact:true}).click();await page.waitForTimeout(800);
 assert.equal(await page.locator('.companion').getAttribute('data-mode'),'wave');
 await page.screenshot({path:path.join(artifacts, 'recording.png')});
 await page.getByLabel('Demo voice activity').uncheck();await page.waitForTimeout(1200);
 assert(await page.locator('.waveform > span').evaluateAll(els=>els.every(el=>parseFloat(el.style.height)===2)));
 await page.getByRole('button',{name:'transcribing',exact:true}).click();await page.waitForTimeout(800);
 assert.equal(await page.locator('.companion').getAttribute('data-mode'),'vortex');
 await page.screenshot({path:path.join(artifacts, 'processing.png')});
 await page.getByRole('button',{name:'cleaning',exact:true}).click();
 assert(await page.locator('.status').innerText()==='Cleaning up');
 await page.getByRole('button',{name:'error',exact:true}).click();assert(await page.locator('.status').innerText()==='Something went wrong');
 await page.getByRole('button',{name:'idle',exact:true}).click();await page.getByLabel('Light background').check();await page.waitForTimeout(800);
 await page.screenshot({path:path.join(artifacts, 'light.png')});
 await page.emulateMedia({reducedMotion:'reduce'});await page.waitForTimeout(50);
 assert.equal(await page.locator('.head-look').evaluate(el=>getComputedStyle(el).transform),'none');
 assert.equal(await page.locator('.smoke-primary').evaluate(el=>getComputedStyle(el).animationName),'none');
 assert.equal(await page.locator('.eyelid.left').evaluate(el=>getComputedStyle(el).animationName),'none');
 assert.deepEqual(errors,[]);
 console.log('PASS: preview assets, idle motion/head direction, recording, quiet waveform, processing/cleanup/error labels, light background, reduced motion; no page errors.');
 await page.close();
 const native=await browser.newPage({viewport:{width:360,height:240}});
 await native.addInitScript(()=>{
  window.testSnapshot={phase:'idle',level:null,inputActive:false,gaze:[0,0]};
  window.testFailure=false;window.concurrent=0;window.maximum=0;
  window.__TAURI_INTERNALS__={invoke:async(cmd)=>{
   if(cmd!=='get_indicator_state')throw Error('Unexpected command: '+cmd);
   window.concurrent++;window.maximum=Math.max(window.maximum,window.concurrent);
   await new Promise(r=>setTimeout(r,70));window.concurrent--;
   if(window.testFailure)throw Error('Fixture disconnection');return {...window.testSnapshot};
  }};
 });
 const nativeErrors=[];native.on('pageerror',e=>nativeErrors.push(e.message));
 await native.goto(baseUrl + '/recording-indicator');await native.locator('.companion').waitFor();
 await native.waitForTimeout(500);
 assert.equal(await native.locator('.companion').getAttribute('data-mode'),'idle');
 assert.equal(await native.evaluate(()=>getComputedStyle(document.body).backgroundColor),'rgba(0, 0, 0, 0)');
 await native.evaluate(()=>{window.testSnapshot={phase:'recording',level:0.25,inputActive:true,gaze:[1,-1]}});
 await native.waitForTimeout(450);assert.equal(await native.locator('.companion').getAttribute('data-mode'),'wave');
 assert(await native.locator('.waveform > span').evaluateAll(els=>els.some(el=>parseFloat(el.style.height)>2)));
 await native.evaluate(()=>{window.testSnapshot.level=null;});await native.waitForTimeout(3500);
 assert.match(await native.locator('.status').innerText(),/meter unavailable/);
 assert(await native.locator('.waveform > span').evaluateAll(els=>els.every(el=>parseFloat(el.style.height)===2)));
 await native.evaluate(()=>{window.testSnapshot.level=0.9;window.testSnapshot.inputActive=false;});await native.waitForTimeout(3500);
 assert.match(await native.locator('.status').innerText(),/No microphone signal/);
 assert(await native.locator('.waveform > span').evaluateAll(els=>els.every(el=>parseFloat(el.style.height)===2)));
 await native.evaluate(()=>{window.testFailure=true;});await native.waitForTimeout(450);
 assert.match(await native.locator('.status').innerText(),/disconnected/);
 await native.evaluate(()=>{window.testFailure=false;window.testSnapshot.phase='idle';});await native.waitForTimeout(500);
 assert.equal(await native.locator('.companion').getAttribute('data-mode'),'idle');
 assert.equal(await native.evaluate(()=>window.maximum),1);
 assert.deepEqual(nativeErrors,[]);
 console.log('PASS: production route with mocked native IPC: transparent body, fresh real levels, unavailable/stale levels settle to zero, disconnect/recovery, persistent idle, serialized polling.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
